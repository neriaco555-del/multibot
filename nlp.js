export function normalizeNaturalCommand(input) {
  const t = (input || '').trim();
  if (!t) return input;
  for (const { re, to } of INTENTS) {
    let m;
    try {
      m = t.match(re);
    } catch {
      continue;
    }
    if (m) {
      const out = (to(m) || '').replace(/[ \t]+/g, ' ').trim();
      if (out && out !== t) return out;
    }
  }
  return input;
}

