export const AI_ALIASES = {
  'מייל': 'אימייל', 'סכם': 'סיכום', 'נסח': 'שכתוב', 'תכנת': 'קוד',
  'פירוש': 'מילון', 'פירוש-חלום': 'חלום', 'הורוסקופ': 'מזל',
};

export function resolveAiTool(cmd) {
  const c = (cmd || '').trim();
  if (AI_TOOLS[c]) return c;
  if (AI_ALIASES[c] && AI_TOOLS[AI_ALIASES[c]]) return AI_ALIASES[c];
  return null;
}

export async function runAiTool(cmd, q) {
  const tool = AI_TOOLS[cmd];
  if (!tool) throw new Error('כלי לא מוכר');
  const clean = (q || '').toString().trim().slice(0, 1500);
  if (tool.needQ && !clean) throw new Error('EMPTY');
  const prompt = tool.prompt.replace('{Q}', clean || 'כללי');
  const { text } = await chatAI(prompt, []);
  return text;
}

export function aiToolUsage(prefix) {
  let out = `✨ *כלי AI — איך משתמשים?*\n\nכתוב את שם הכלי + טקסט (חלק מהכלים עובדים גם בלי טקסט).\n\n`;
  for (const [name, t] of Object.entries(AI_TOOLS)) {
    out += `• ${prefix}${name}${t.needQ ? ' <טקסט>' : ' [טקסט]'} — ${t.hint}\n`;
  }
  out += `\n📌 *דוגמאות:*\n• ${prefix}בדיחה\n• ${prefix}ברכה יום הולדת לאבא\n• ${prefix}מתכון פנקייק`;
  return out;
}
